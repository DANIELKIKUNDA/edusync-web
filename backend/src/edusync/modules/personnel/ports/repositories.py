from __future__ import annotations
from typing import Protocol
from uuid import UUID
from edusync.modules.personnel.domain.models import StaffAssignment, StaffFunction, StaffMember, StaffSummary

class PersonnelRepository(Protocol):
    def get_staff(self, school_id: UUID, staff_id: UUID) -> dict | None: ...
    def list_staff(self, school_id: UUID, *, query: str | None = None, status: str | None = None, category: str | None = None, scope_types: tuple[tuple[str,str|None], ...] = ()) -> list[dict]: ...
    def summary(self, school_id: UUID, *, scope_types: tuple[tuple[str,str|None], ...] = ()) -> StaffSummary: ...
    def create_staff(self, member: StaffMember) -> dict: ...
    def update_staff(self, school_id: UUID, staff_id: UUID, *, expected_version: int, fields: dict) -> dict: ...
    def create_function(self, function: StaffFunction) -> dict: ...
    def list_functions(self, school_id: UUID, *, enabled_only: bool = False) -> list[dict]: ...
    def add_assignment(self, assignment: StaffAssignment) -> dict: ...
