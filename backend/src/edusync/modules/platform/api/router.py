@router.get('/schools/export.csv')
def platform_schools_export(q: str|None=None, status: str|None=None, config: str|None=None, needs_admin: bool=False, sort: str='name',
                            actor: ActorContext = Depends(require_platform_actor), services: AppServices = Depends(get_services)):
    """CSV of the filtered directory (same filters as the list), UTF-8 with BOM, formula-injection safe, audited."""
    actor.require('platform.schools.read')
    import csv, io
    from fastapi.responses import Response as _Resp
    from edusync.modules.audit.domain.audit import AuditRecord
    from edusync.modules.platform.application.schools_directory import CONFIG_STATES, SORTS, list_schools
    if (status and status not in ('ACTIVE', 'SUSPENDED', 'DISABLED')) or (config and config not in CONFIG_STATES) or sort not in SORTS:
        raise HTTPException(422, 'Filtre inconnu')
    labels = {'ACTIVE': 'Active', 'SUSPENDED': 'Suspendue', 'DISABLED': 'Désactivée', 'COMPLETE': 'Configuration complète',
              'INCOMPLETE': 'À finaliser', 'ADMIN_PENDING': 'Activation en attente', 'ADMIN_MISSING': 'Administrateur à créer'}
    safe = lambda v: ("'" + v) if isinstance(v, str) and v[:1] in ('=', '+', '-', '@', '\t', '\r') else ('' if v is None else v)  # noqa: E731
    rows, cursor = [], None
    with services.platform_db.platform_transaction() as c:
        while len(rows) < 10000:
            page = list_schools(c, q=q, status=status or None, config=config or None, needs_admin=needs_admin, sort=sort, cursor=cursor, limit=100)
            rows += page['items']
            cursor = page['next_cursor']
            if not cursor: break
        PostgresAuditRepository(c).append(AuditRecord(action='PLATFORM_SCHOOLS_EXPORTED', entity_type='School', entity_id=None, actor_user_id=actor.user_id,
            school_id=None, source=actor.source, new_data={'rows': len(rows), 'q': q, 'status': status, 'config': config, 'needs_admin': needs_admin}))
    buf = io.StringIO(); w = csv.writer(buf, delimiter=';')
    w.writerow(['Nom de l’école', 'Code EduSync', 'Promoteur / contact', 'Téléphone du contact', 'Province', 'Ville', 'Statut', 'Configuration', 'Utilisateurs actifs', 'Créée le'])
    for r in rows:
        w.writerow([safe(r['name']), safe(r['code']), safe(r['contact_name']), safe(r['contact_phone_display']), safe(r['province']), safe(r['city']),
                    labels[r['status']], labels[r['config_state']], r['users_count'], r['created_at'].date().isoformat()])
    return _Resp(content='\ufeff' + buf.getvalue(), media_type='text/csv; charset=utf-8',
                 headers={'Content-Disposition': 'attachment; filename="ecoles-edusync.csv"', 'Cache-Control': 'no-store'})


@router.patch('/schools/{school_id}')
def platform_update_school(school_id: UUID, body: SchoolUpdate, actor: ActorContext = Depends(require_platform_actor), services: AppServices = Depends(get_services)):
    """Identity and promoter / main contact of a school (capability platform.schools.update), optimistic, audited.
    A disabled school is not edited from the platform (only the actions the business allows)."""
    actor.require('platform.schools.update')
    clean = _clean_identity(body)
    from sqlalchemy import text
    from edusync.modules.audit.domain.audit import AuditRecord
    cols = ('name', 'province', 'city', 'address', 'email', 'phone', 'contact_name', 'contact_function', 'contact_phone', 'contact_email')
    with services.platform_db.platform_transaction() as c:
        old = c.execute(text("SELECT status, version, " + ", ".join(cols) + " FROM schools WHERE id=:id FOR UPDATE"), {'id': school_id}).mappings().first()
        if not old: raise HTTPException(404, 'École introuvable')
        if old['status'] == 'DISABLED': raise HTTPException(409, 'Une école désactivée ne se modifie pas depuis la plateforme.')
        if int(old['version']) != body.version: raise HTTPException(409, 'Cette école a été modifiée entre-temps : rechargez la fiche.')
        row = c.execute(text("UPDATE schools SET " + ", ".join(f"{k}=:{k}" for k in cols) + ", updated_at=now(), version=version+1 WHERE id=:id AND version=:v RETURNING version"),
                        {**clean, 'id': school_id, 'v': body.version}).first()
        changed = {k: {'avant': old[k], 'après': clean[k]} for k in cols if old[k] != clean[k]}
        PostgresAuditRepository(c).append(AuditRecord(action='PLATFORM_SCHOOL_UPDATED', entity_type='School', entity_id=school_id, actor_user_id=actor.user_id,
            school_id=school_id, source=actor.source, old_data={k: v['avant'] for k, v in changed.items()}, new_data={k: v['après'] for k, v in changed.items()}))
    return {'id': str(school_id), 'version': int(row[0]), 'changed': sorted(changed)}


@router.post('/schools/{school_id}/admins/{membership_id}/reset-access')
def platform_reset_admin_access(school_id: UUID, membership_id: UUID, body: AccessReset, response: Response, actor: ActorContext = Depends(require_platform_actor),
                                services: AppServices = Depends(get_services)):
    """Administrative continuity: a school administrator who lost access (phone, password, departure handled later by the
    school) gets a new temporary password shown once — or an e-mail link — and all their sessions are closed.
    Only for an active school administrator of this school; step-up code required; audited."""
    actor.require('platform.school_admin.bootstrap')
    require_recent_mfa(services, actor, 'platform.school_admin.bootstrap')
    from sqlalchemy import text
    from edusync.modules.audit.domain.audit import AuditRecord
    from edusync.modules.iam.application import account_links
    from edusync.shared.infrastructure.security import hash_password, new_temporary_password
    invite = body.delivery == 'INVITATION'
    if invite and not account_links.email_available(services.settings):
        raise HTTPException(409, 'L’envoi d’e-mails n’est pas disponible : utilisez un mot de passe provisoire.')
    temporary = None
    with services.platform_db.platform_transaction() as c:
        target = c.execute(text("""SELECT u.id, u.email, u.full_name, u.active FROM school_memberships m JOIN users u ON u.id=m.user_id
            JOIN rbac_assignments a ON a.membership_id=m.id AND a.active JOIN rbac_roles r ON r.id=a.role_id AND r.code=:admin
            WHERE m.id=:mid AND m.school_id=:sid AND m.active FOR UPDATE OF u"""), {'mid': membership_id, 'sid': school_id, 'admin': SCHOOL_ADMIN_ROLE}).mappings().first()
        if not target or not target['active']: raise HTTPException(404, 'Administrateur actif de cette école introuvable')
        other_schools = c.execute(text("SELECT count(*) FROM school_memberships WHERE user_id=:u AND active AND school_id<>:sid"), {'u': target['id'], 'sid': school_id}).scalar_one()
        if other_schools or c.execute(text("SELECT 1 FROM rbac_assignments WHERE user_id=:u AND school_id IS NULL AND active"), {'u': target['id']}).first():
            raise HTTPException(409, 'Ce compte donne accès à d’autres espaces : son mot de passe ne peut pas être réinitialisé depuis cette école.')
        if invite:
            c.execute(text("UPDATE users SET password_hash=:p, must_change_password=false, version=version+1 WHERE id=:u"),
                      {'p': hash_password(new_temporary_password() + new_temporary_password()), 'u': target['id']})
