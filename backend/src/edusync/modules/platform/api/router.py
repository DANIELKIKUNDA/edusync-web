def _school_json(s):
    return {
        "id": str(s.id), "name": s.name, "code": s.code, "status": s.status.value,
        "logo_url": s.logo_url, "email": s.email, "phone": s.phone,
        "address": s.address, "city": s.city, "province": s.province,
        "contact_name": s.contact_name, "contact_function": s.contact_function, "contact_phone": s.contact_phone,
        "contact_email": s.contact_email,
        "created_at": s.created_at.isoformat(), "updated_at": s.updated_at.isoformat(),
        "version": s.version,
    }


def _clean_identity(body: "SchoolCreate") -> dict:
    """Trimmed, normalized identity (province from the reference list, phones in E.164); 422 with a clear message."""
    from edusync.modules.platform.application.schools_directory import normalize_phone, normalize_province
    t = lambda v: (v or "").strip() or None  # noqa: E731
    try:
        out = {"name": body.name.strip(), "province": normalize_province(body.province), "city": t(body.city), "address": t(body.address),
               "email": t(body.email), "phone": normalize_phone(body.phone), "contact_name": t(body.contact_name),
               "contact_function": t(body.contact_function), "contact_phone": normalize_phone(body.contact_phone),
               "contact_email": t(body.contact_email)}
    except ValueError as exc:
        raise HTTPException(422, str(exc)) from exc
    if len(out["name"]) < 2:
        raise HTTPException(422, "Le nom de l’école est obligatoire.")
    if not out["province"]:
        raise HTTPException(422, "La province est obligatoire.")
    return out


def _mutation_error(exc: Exception):
    if isinstance(exc, LookupError):
        raise HTTPException(status_code=404, detail=str(exc)) from exc
    if isinstance(exc, (ValueError, OptimisticConcurrencyError, IdempotencyConflict)):
        raise HTTPException(status_code=409, detail=str(exc)) from exc
    if isinstance(exc, IntegrityError):
        raise HTTPException(status_code=409, detail="Conflit d'unicité ou de référence; rechargez les données") from exc
    if isinstance(exc, IdempotencyInProgress):
        raise HTTPException(status_code=409, detail=str(exc), headers={"Retry-After": "1"}) from exc
    if isinstance(exc, PermissionError):
        raise HTTPException(status_code=403, detail=str(exc)) from exc
    raise exc


def _key(value: str | None) -> str:
    key = (value or "").strip()
    if not key:
        raise HTTPException(status_code=400, detail="En-tête Idempotency-Key obligatoire pour cette mutation")
    if len(key) > 180:
        raise HTTPException(status_code=400, detail="Idempotency-Key trop longue")
    return key


