@router.post("/schools/{school_id}/bootstrap-admin", status_code=201)
def bootstrap_admin(
    school_id: UUID,
    body: AdminBootstrap,
    response: Response,
    idempotency_key: str | None = Header(default=None, alias="Idempotency-Key"),
    actor: ActorContext = Depends(require_platform_actor),
    services: AppServices = Depends(get_services),
):
    key = _key(idempotency_key)
    require_recent_mfa(services, actor, "platform.school_admin.bootstrap")  # step-up: code confirmed in the last minutes
    request_actor = replace(actor, correlation_id=uuid4(), idempotency_key=key)
    from edusync.modules.iam.application import account_links
    from edusync.shared.infrastructure.security import new_temporary_password
    from sqlalchemy import text as _text
    invite = body.delivery == "INVITATION"
    if invite and not account_links.email_available(services.settings):
        raise HTTPException(409, "L’envoi d’e-mails n’est pas disponible : utilisez un mot de passe provisoire.")
    payload = {"school_id": str(school_id), "email": body.email.strip().lower(), "full_name": body.full_name.strip(), "delivery": body.delivery}
    issued: dict = {}   # the temporary password lives only in this request: never stored, never audited
    try:
        with services.platform_db.platform_transaction() as conn:
            schools = PostgresSchoolRepository(conn)
            users = PostgresUserRepository(conn)
            memberships = PostgresMembershipRepository(conn)
            audit = PostgresAuditRepository(conn)
            outbox = PostgresOutboxRepository(conn)
            idem = IdempotentExecutor(PostgresIdempotencyRepository(conn))

            def action():
                existed = users.get_by_email(payload["email"]) is not None
                temporary = new_temporary_password()
                user, membership = BootstrapSchoolAdmin(
                    schools, users, memberships, audit, outbox
                ).execute(request_actor, BootstrapSchoolAdminCommand(school_id=school_id, email=payload["email"],
                                                                     full_name=payload["full_name"], password=temporary))
                out = {"user_id": str(user.id), "membership_id": str(membership.id), "school_id": str(school_id),
                       "role": "ADMIN_SYSTEME_ECOLE", "account": "EXISTING_ACCOUNT_ATTACHED" if existed else "CREATED", "delivery": body.delivery}
                if not existed and invite:
                    # The person chooses the password through the link; the random bootstrap secret is never shown.
                    conn.execute(_text("UPDATE users SET must_change_password=false WHERE id=:u"), {"u": str(user.id)})
                    raw = account_links.issue(conn, services.settings, user_id=user.id, purpose=account_links.INVITATION,
                                              school_id=school_id, membership_id=membership.id, created_by=actor.user_id)
                    account_links.send_link_email(conn, services.settings, user_id=user.id, email=payload["email"], full_name=payload["full_name"],
                                                  purpose=account_links.INVITATION, raw=raw, school_id=school_id, created_by=actor.user_id)
                    out["invitation_sent"] = True
                elif not existed:
                    issued["temporary_password"] = temporary
                return 201, out

            result = idem.execute(
                scope_key="platform", idempotency_key=key, operation="PLATFORM_BOOTSTRAP_SCHOOL_ADMIN",
                payload=payload, school_id=None, actor_user_id=str(actor.user_id), action=action,
            )
        response.status_code = result.status_code
        response.headers["Idempotent-Replayed"] = "true" if result.replayed else "false"
        response.headers["Cache-Control"] = "no-store"
        # Shown once. A replay (double click, lost response) never returns it again: reset the access if needed.
        return {**result.body, "temporary_password": issued.get("temporary_password")}
    except Exception as exc:
        _mutation_error(exc)


