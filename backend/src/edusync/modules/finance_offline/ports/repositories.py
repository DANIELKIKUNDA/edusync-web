from __future__ import annotations

from decimal import Decimal
from typing import Protocol, Iterable
from uuid import UUID

from edusync.modules.finance_offline.domain.models import (
    ChargeSnapshot, OfflineFinanceLease, OfflinePaymentCommand, ReceiptToken
)
from edusync.modules.finance_offline.domain.multi_cashier import (
    JournalCheckpoint, OfflinePostingResult, ReceivedCommandRecord
)


class OfflineFinanceRepository(Protocol):
    # V1 compatibility surface (kept for migration history/tests).
    def acquire_exclusive_lease(self, *, school_id: UUID, cashier_user_id: UUID, device_id: UUID,
                                cash_session_id: UUID, max_payments: int, max_cdf: str, max_usd: str,
                                receipt_count: int, local_minutes: int) -> tuple[OfflineFinanceLease, list[ReceiptToken]]: ...
    def blocking_lease(self, school_id: UUID) -> OfflineFinanceLease | None: ...
    def store_charge_snapshots(self, lease_id: UUID, snapshots: Iterable[ChargeSnapshot]) -> None: ...
    def activate_lease(self, lease_id: UUID) -> OfflineFinanceLease: ...

    # Point 2 / V2 canonical multi-cashier surface.
    def acquire_multi_writer_lease(self, *, school_id: UUID, cashier_user_id: UUID, device_id: UUID,
                                   cash_session_id: UUID, max_payments: int, max_cdf: str, max_usd: str,
                                   receipt_count: int, local_minutes: int) -> tuple[OfflineFinanceLease, list[ReceiptToken]]: ...
    def reserve_charge_snapshots(self, lease_id: UUID, snapshots: Iterable[ChargeSnapshot]) -> None: ...
    def activate_multi_writer_lease(self, lease_id: UUID) -> OfflineFinanceLease: ...
    def lock_lease_for_sync(self, lease_id: UUID) -> None: ...
    def journal_checkpoint(self, lease_id: UUID) -> JournalCheckpoint: ...
    def received_command(self, *, school_id: UUID, operation_id: UUID) -> ReceivedCommandRecord | None: ...
    def assert_server_lease_limits(self, lease_id: UUID) -> None: ...
    def consume_charge_reservations(self, command: OfflinePaymentCommand) -> None: ...
    def resolve_quarantine(self, lease_id: UUID, *, actor_user_id: UUID, reason: str) -> None: ...

    def receipt_token(self, token_id: UUID) -> ReceiptToken | None: ...
    def consume_receipt_token(self, *, token_id: UUID, lease_id: UUID, operation_id: UUID) -> None: ...
    def store_received_command(self, command: OfflinePaymentCommand) -> bool: ...
    def mark_command_applied(self, operation_id: UUID, *, payment_id: UUID | None = None,
                             posting_outcome: str = "APPLIED",
                             residual_credit_amount: Decimal | str = "0.00") -> None: ...
    def mark_lease_draining(self, lease_id: UUID) -> None: ...
    def close_lease_if_reconciled(self, lease_id: UUID, *, expected_count: int, expected_cdf: str, expected_usd: str,
                                  final_entry_hash: str | None) -> None: ...
    def force_release(self, lease_id: UUID, *, actor_user_id: UUID, reason: str) -> None: ...


class OfflineChargeSnapshotRepository(Protocol):
    def snapshots_for_lease(self, lease_id: UUID) -> Iterable[ChargeSnapshot]: ...


class OfflinePaymentPostingPort(Protocol):
    """Hexagonal port into canonical Finance.

    Point 2 hard rule: the implementation posts physical CASH exactly once in the SAME
    PostgreSQL transaction as exact allocations, official receipt, cash movement, audit and
    outbox. If a legitimate offline receipt reaches a charge whose actual server balance is
    unexpectedly lower, the adapter must allocate the still-due amount and book the remainder
    as an explicit same-currency residual credit; it must never silently lose cash or fabricate
    a second debt payment.
    """
    def post(self, command: OfflinePaymentCommand) -> UUID | OfflinePostingResult: ...
