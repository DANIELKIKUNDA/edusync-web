from __future__ import annotations
from typing import Protocol
from uuid import UUID
from edusync.modules.schooling.domain.models import Family, Guardian, Enrollment, Student, StudentBenefit

class SchoolingRepository(Protocol):
    def next_code(self, namespace:str, prefix:str)->str: ...
    def create_family(self, family:Family)->dict: ...
    def create_guardian(self, guardian:Guardian)->dict: ...
    def link_guardian(self, *, family_id:UUID, guardian_id:UUID, role:str, is_primary:bool)->dict: ...
    def create_student(self, student:Student)->dict: ...
    def create_enrollment(self, enrollment:Enrollment)->dict: ...
    def add_benefit(self, benefit:StudentBenefit)->dict: ...
    def get_student(self, student_id:UUID)->dict|None: ...
    def get_family(self, family_id:UUID)->dict|None: ...
