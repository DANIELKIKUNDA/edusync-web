def team_create_user(body: UserCreate, response: Response, idempotency_key: str | None = Header(default=None),
                     actor: ActorContext = Depends(require_platform_actor), services: AppServices = Depends(get_services)):
    """« Nouvelle identité »: e-mail invitation (the person chooses the password, then enrols the second factor) when
    e-mail is available; otherwise a temporary password generated by the server, returned once, never stored in clear,
    never audited, to be replaced at the first sign-in. A replay (same Idempotency-Key) never returns the password."""
    from edusync.modules.iam.application import account_links
    actor.require(TEAM_CAP)
    require_recent_mfa(services, actor)  # step-up: code confirmed in the last minutes
    key = _key(idempotency_key)
    response.headers["Cache-Control"] = "no-store"
    email = body.email.strip().lower()
    invite = body.delivery == "INVITATION"
    if invite and not account_links.email_available(services.settings):
        raise HTTPException(422, "L’envoi d’e-mails n’est pas configuré : choisissez le mot de passe provisoire.")
    issued: dict = {}
    try:
        with services.platform_db.platform_transaction() as c:
            prior = _replayed(c, actor, key, "PLATFORM_USER_CREATED")
            if prior:
                return prior
            roles = _assignable_roles(c, actor, body.role_codes)
            if c.execute(text("SELECT 1 FROM users WHERE lower(email::text)=:e"), {"e": email}).first():
                raise HTTPException(409, "Un compte EduSync existe déjà avec cette adresse : ajoutez-le comme « Utilisateur existant ».")
            # invitation: an unusable random password until the person chooses one through the single-use link
            secret = secrets.token_urlsafe(32) if invite else new_temporary_password()
            uid = c.execute(text("""INSERT INTO users(email,full_name,password_hash,active,is_platform_admin,must_change_password,password_set_by)
                VALUES(:e,:n,:p,true,true,:mcp,'PLATFORM') RETURNING id"""),
                {"e": email, "n": body.full_name.strip(), "p": hash_password(secret), "mcp": not invite}).scalar_one()
            _attach_roles(c, actor, uid, roles, body.reason)
            if invite:
                raw = account_links.issue(c, services.settings, user_id=uid, purpose=account_links.INVITATION, created_by=actor.user_id)
                account_links.send_link_email(c, services.settings, user_id=uid, email=email, full_name=body.full_name.strip(),
                                              purpose=account_links.INVITATION, raw=raw, created_by=actor.user_id)
            else:
                issued["temporary_password"] = secret
            result = {"id": str(uid), "email": email, "full_name": body.full_name.strip(), "roles": [r["code"] for r in roles],
                      "delivery": body.delivery, "origin": "NEW_IDENTITY"}
            _audit(c, actor, "PLATFORM_USER_CREATED", "User", uid, reason=body.reason, new=result, key=key)
    except IntegrityError as exc:   # two simultaneous creations of the same address: the unique e-mail index decides
        raise HTTPException(409, "Un compte EduSync existe déjà avec cette adresse : ajoutez-le comme « Utilisateur existant ».") from exc
    return {**result, "temporary_password": issued.get("temporary_password")}


