_MEMBER = """EXISTS (SELECT 1 FROM rbac_assignments ma JOIN rbac_roles mr ON mr.id=ma.role_id
                WHERE ma.user_id=u.id AND ma.school_id IS NULL AND ma.active AND mr.level='PLATFORM')"""
_PENDING = """(coalesce(u.must_change_password,false) OR EXISTS (SELECT 1 FROM account_tokens pt WHERE pt.user_id=u.id
               AND pt.purpose='INVITATION' AND pt.school_id IS NULL AND pt.used_at IS NULL AND pt.revoked_at IS NULL AND pt.expires_at>now()))"""
_SUSPENDED = "EXISTS (SELECT 1 FROM platform_account_status ss WHERE ss.user_id=u.id AND ss.status='SUSPENDED')"
_MEMBER_STATUS = {"SUSPENDED": _SUSPENDED, "PENDING": "NOT " + _SUSPENDED + " AND " + _PENDING,
                  "ACTIVE": "u.active AND NOT " + _SUSPENDED + " AND NOT " + _PENDING}
_SEARCH_KEY = "edusync_search_key(u.full_name || ' ' || u.email::text)"


def _search(q: str | None) -> tuple[list[str], dict]:
    words = [w for w in re.split(r"[\s\-'’.,;:/]+", (q or "").strip()) if w][:5]
    return ([_SEARCH_KEY + f" LIKE '%' || edusync_search_key(CAST(:w{i} AS text)) || '%'" for i in range(len(words))],
            {f"w{i}": w for i, w in enumerate(words)})


def _cursor_out(row) -> str:
    return base64.urlsafe_b64encode(json.dumps([row["full_name"].lower(), str(row["id"])]).encode()).decode().rstrip("=")


def _cursor_in(cursor: str | None) -> dict | None:
    if not cursor:
        return None
    try:
        k1, kid = json.loads(base64.urlsafe_b64decode(cursor + "=" * (-len(cursor) % 4)))
        if not isinstance(k1, str):
            raise ValueError
        return {"k1": k1, "kid": str(UUID(str(kid)))}
    except Exception as exc:  # noqa: BLE001 — forged or stale cursor
        raise HTTPException(422, "Curseur de pagination invalide") from exc


_USERS_PAGE = """
WITH page AS (
  SELECT u.id, u.email::text AS email, u.full_name, u.active AS account_active, u.created_at, u.must_change_password
    FROM users u WHERE {where} ORDER BY lower(u.full_name), u.id LIMIT :lim
)
SELECT u.id, u.email, u.full_name, u.account_active, u.created_at,
       coalesce(ps.status,'ACTIVE') AS platform_status,
       CASE WHEN NOT u.account_active THEN 'DISABLED' WHEN coalesce(ps.status,'ACTIVE')='SUSPENDED' THEN 'SUSPENDED'
            WHEN {pending} THEN 'PENDING' ELSE 'ACTIVE' END AS status,
       rl.roles, rl.role_labels, gr.grants_count,
       (SELECT max(d.last_seen_at) FROM user_device_sessions d WHERE d.user_id=u.id AND d.school_id IS NULL) AS last_activity,
       EXISTS (SELECT 1 FROM user_mfa_factors f WHERE f.user_id=u.id AND f.status='ACTIVE') AS mfa_enrolled,
       {invitation} AS invitation_state
  FROM page u
  LEFT JOIN platform_account_status ps ON ps.user_id=u.id
  LEFT JOIN LATERAL (SELECT coalesce(array_agg(r.code ORDER BY lower(r.label)) FILTER (WHERE r.status='ACTIVE'), '{{}}') roles,
                            coalesce(array_agg(r.label ORDER BY lower(r.label)) FILTER (WHERE r.status='ACTIVE'), '{{}}') role_labels
         FROM rbac_assignments a JOIN rbac_roles r ON r.id=a.role_id
        WHERE a.user_id=u.id AND a.school_id IS NULL AND a.active AND r.level='PLATFORM') rl ON true
  LEFT JOIN LATERAL (SELECT count(*) grants_count FROM platform_capability_grants g
        WHERE g.user_id=u.id AND g.active AND (g.valid_until IS NULL OR g.valid_until>now())) gr ON true
 ORDER BY lower(u.full_name), u.id
"""


@router.get("/users")
def team_users(q: str | None = None, status: str | None = None, role: str | None = None, cursor: str | None = None, limit: int = 25,
               actor: ActorContext = Depends(require_platform_actor), services: AppServices = Depends(get_services)):
    """Members of the platform team (active platform role assignment): instant server-side search on name and e-mail
    (trigram index), status (ACTIVE / PENDING first sign-in not done / SUSPENDED), role, keyset pagination."""
    actor.require(TEAM_CAP)
    if (status and status not in _MEMBER_STATUS) or (role and not CODE_RE.match(role)) or (q and len(q) > 80):
        raise HTTPException(422, "Filtre inconnu")
    limit = max(1, min(limit, 100))
    where, params = _search(q)
    where.append(_MEMBER)
    if status:
        where.append(_MEMBER_STATUS[status])
    if role:
        where.append("""EXISTS (SELECT 1 FROM rbac_assignments fa JOIN rbac_roles fr ON fr.id=fa.role_id AND fr.code=:role
                         WHERE fa.user_id=u.id AND fa.school_id IS NULL AND fa.active)""")
        params["role"] = role
    from edusync.modules.iam.application import account_links
    with services.platform_db.platform_transaction() as c:
        _sweep_expired_grants(c)
        total = int(c.execute(text("SELECT count(*) FROM users u WHERE " + " AND ".join(where)), params).scalar_one())
        key = _cursor_in(cursor)
        page_where = list(where)
        if key:
            page_where.append("(lower(u.full_name), u.id) > (CAST(:k1 AS text), CAST(:kid AS uuid))")
            params |= key
        sql = _USERS_PAGE.format(where=" AND ".join(page_where), pending=_PENDING, invitation=_INVITATION_STATE.replace("{u}", "u.id"))
        rows = [dict(r) for r in c.execute(text(sql), params | {"lim": limit + 1}).mappings()]
        managers = _active_managers(c)
    more = len(rows) > limit
    rows = rows[:limit]
    return {"items": [{**r, "roles": list(r["roles"]), "role_labels": list(r["role_labels"]), "grants_count": int(r["grants_count"]),
                       "is_me": r["id"] == actor.user_id} for r in rows],
            "total": total, "has_more": more, "next_cursor": _cursor_out(rows[-1]) if more and rows else None, "limit": limit,
            "active_managers": managers, "email_invitations_available": account_links.email_available(services.settings)}


