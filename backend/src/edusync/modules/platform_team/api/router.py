def _assignable_roles(c, actor: ActorContext, codes: list[str]) -> list[dict]:
    roles = []
    for code in sorted(set(x.strip().upper() for x in codes)):
        role = _role(c, code=code)
        if not role or role["status"] != "ACTIVE":
            raise HTTPException(422, f"Rôle plateforme actif introuvable : {code}")
        if set(role["capabilities"]) - actor.permissions:
            raise HTTPException(403, f"Vous ne pouvez pas attribuer le rôle {role['label']} : il contient des capacités que vous n’avez pas.")
        roles.append(role)
    return roles


def _attach_roles(c, actor: ActorContext, user_id, roles: list[dict], reason: str) -> None:
    for role in roles:
        existing = c.execute(text("""SELECT id, active FROM rbac_assignments WHERE user_id=:u AND role_id=:r AND school_id IS NULL
            ORDER BY created_at DESC LIMIT 1 FOR UPDATE"""), {"u": str(user_id), "r": role["id"]}).mappings().first()
        if existing and existing["active"]:
            continue
        if existing:
            c.execute(text("""UPDATE rbac_assignments SET active=true, valid_from=now(), valid_until=NULL, granted_by_user_id=:by, reason=:reason,
                version=version+1, updated_at=now() WHERE id=:id"""), {"id": existing["id"], "by": str(actor.user_id), "reason": reason})
        else:
            aid = c.execute(text("INSERT INTO rbac_assignments(user_id,role_id,granted_by_user_id,reason) VALUES(:u,:r,:by,:reason) RETURNING id"),
                            {"u": str(user_id), "r": role["id"], "by": str(actor.user_id), "reason": reason}).scalar_one()
            c.execute(text("INSERT INTO rbac_assignment_scopes(assignment_id,scope_type,scope_value) VALUES(:id,'PLATFORM',NULL)"), {"id": aid})
    c.execute(text("UPDATE users SET is_platform_admin=true WHERE id=:u"), {"u": str(user_id)})
    c.execute(text("""INSERT INTO platform_account_status(user_id,status,reason,changed_by_user_id) VALUES(:u,'ACTIVE',:r,:by)
        ON CONFLICT (user_id) DO UPDATE SET status='ACTIVE', reason=EXCLUDED.reason, changed_by_user_id=EXCLUDED.changed_by_user_id,
          changed_at=now(), version=platform_account_status.version+1"""), {"u": str(user_id), "r": reason, "by": str(actor.user_id)})


