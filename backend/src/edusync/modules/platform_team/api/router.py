@router.post("/users/{user_id}/platform-access/revoke")
def team_remove_access(user_id: UUID, body: ReasonInput, idempotency_key: str | None = Header(default=None),
                       actor: ActorContext = Depends(require_platform_actor), services: AppServices = Depends(get_services)):
    """Removes the platform access (unlike a suspension, which is temporary and keeps everything): every platform role
    assignment and individual capability ends, platform sessions and open platform invitations are revoked. The global
    identity, school memberships, local roles and school data are never touched."""
    actor.require(TEAM_CAP)
    require_recent_mfa(services, actor)
    key = _key(idempotency_key)
    with services.platform_db.platform_transaction() as c:
        prior = _replayed(c, actor, key, "PLATFORM_ACCESS_REVOKED")
        if prior:
            return prior
        # Serialise Manager changes (first, before any row lock): two concurrent removals never leave zero active Manager.
        c.execute(text("SELECT pg_advisory_xact_lock(hashtext('edusync:platform:managers'))"))
        c.execute(text("SELECT 1 FROM users WHERE id=:u FOR UPDATE"), {"u": str(user_id)})
        _guard_target(c, actor, user_id)
        if not _is_member(c, user_id):
            raise HTTPException(404, "Ce compte n’a pas d’accès plateforme.")
        if MANAGER_ROLE in _active_role_codes(c, user_id) and _active_managers(c, exclude_user=user_id) == 0:
            raise HTTPException(409, "Impossible : ce compte est le dernier Manager système actif.")
        roles = list(c.execute(text("""UPDATE rbac_assignments a SET active=false, reason=:r, version=a.version+1, updated_at=now()
            FROM rbac_roles r WHERE r.id=a.role_id AND r.level='PLATFORM' AND a.user_id=:u AND a.school_id IS NULL AND a.active
            RETURNING r.code"""), {"u": str(user_id), "r": body.reason}).scalars())
        grants = _end_grants(c, user_id, actor, "ACCESS_REMOVED", body.reason)
        c.execute(text("UPDATE users SET is_platform_admin=false WHERE id=:u"), {"u": str(user_id)})
        sessions = _revoke_platform_sessions(c, user_id, "PLATFORM_ACCESS_REVOKED")
        invitations = c.execute(text("""UPDATE account_tokens SET revoked_at=now(), revoked_reason='PLATFORM_ACCESS_REVOKED'
            WHERE user_id=:u AND purpose='INVITATION' AND school_id IS NULL AND used_at IS NULL AND revoked_at IS NULL"""), {"u": str(user_id)}).rowcount
        schools = int(c.execute(text("SELECT count(*) FROM school_memberships WHERE user_id=:u AND active"), {"u": str(user_id)}).scalar_one())
        result = {"user_id": str(user_id), "roles_ended": sorted(roles), "capabilities_ended": sorted(grants), "sessions_revoked": sessions,
                  "invitations_revoked": invitations, "school_memberships_kept": schools}
        _audit(c, actor, "PLATFORM_ACCESS_REVOKED", "User", user_id, reason=body.reason,
               old={"roles": sorted(roles), "capabilities": sorted(grants)}, new=result, key=key)
    return result


