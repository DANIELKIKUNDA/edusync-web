"""Plateforme EduSync — governance of the platform team (N1 certification 2026-10, Équipe plateforme lot 2026-10).

Platform accounts, PLATFORM_CUSTOM roles, assignments, individual capabilities, suspension, platform access removal,
invitations, sessions and password reset.

Anti-escalation rules (enforced here, and partly in the database by migration 0052):
  * every team mutation requires `platform.collaborators.manage` (reserved capability, never delegable);
  * a role can only be given capabilities the actor holds, never a reserved one, only PLATFORM-scoped ones;
  * nobody changes their own roles, status or password through these routes (self-service is /auth/platform/*);
  * an actor cannot act on an account holding capabilities the actor lacks;
  * the last active Manager système can be neither suspended nor stripped of the role nor of the platform access
    (serialised by an advisory lock: two concurrent requests can never leave zero active Manager);
  * an individual capability only supplements a platform role; it follows the delegation rules of the custom roles
    (platform-scoped, never reserved, held by the actor) and is enforced again by the database (migration 0080).
Effective capabilities = UNION(active platform roles) ∪ (valid individual grants), recomputed on every request: a
revocation counts at the next call. Every mutation is audited (actor, target, before/after, reason, idempotency key).
Suspension (temporary, roles and capabilities kept) and platform access removal (roles and individual capabilities
ended, school memberships and local roles untouched) are distinct operations.
"""
