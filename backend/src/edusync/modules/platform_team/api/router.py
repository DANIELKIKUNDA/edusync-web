def _role_caps(c, codes: list[str]) -> dict[str, dict]:
    if not codes:
        return {}
    rows = c.execute(text("""SELECT r.code, r.label, coalesce(array_agg(rc.capability_code) FILTER (WHERE rc.capability_code IS NOT NULL), '{}') caps
        FROM rbac_roles r LEFT JOIN rbac_role_capabilities rc ON rc.role_id=r.id
        WHERE r.level='PLATFORM' AND r.code = ANY(:codes) GROUP BY r.code, r.label"""), {"codes": codes}).mappings().all()
    return {r["code"]: {"label": r["label"], "caps": set(r["caps"])} for r in rows}


def _rights_summary(c, user_id: UUID) -> dict:
    """Why does this account hold each capability? Every origin is listed once per capability (role or grant)."""
    catalog = _platform_catalog(c)
    roles = _role_caps(c, _active_role_codes(c, user_id))
    grants = [dict(r) for r in c.execute(text("""SELECT g.capability_code, g.valid_from, g.valid_until, g.reason, g.created_at,
          u.full_name AS granted_by FROM platform_capability_grants g LEFT JOIN users u ON u.id=g.granted_by_user_id
        WHERE g.user_id=:u AND g.active AND (g.valid_until IS NULL OR g.valid_until>now()) ORDER BY g.capability_code"""),
        {"u": str(user_id)}).mappings()]
    origins: dict[str, list[dict]] = {}
    for code, role in sorted(roles.items(), key=lambda kv: kv[1]["label"].lower()):
        for cap in role["caps"]:
            origins.setdefault(cap, []).append({"kind": "ROLE", "code": code, "label": role["label"]})
    inherited = set(origins)
    if roles:   # without an active role, an individual grant counts for nothing (platform_permissions)
        for g in grants:
            origins.setdefault(g["capability_code"], []).append({"kind": "GRANT", "granted_by": g["granted_by"], "granted_at": g["created_at"],
                                                                 "valid_until": g["valid_until"], "reason": g["reason"]})
    items = [{"code": code, "label": catalog.get(code, {}).get("label", code), "group_name": catalog.get(code, {}).get("group_name", "Autres"),
              "risk": catalog.get(code, {}).get("risk"), "origins": src} for code, src in sorted(origins.items())]
    supplementary = sorted({g["capability_code"] for g in grants} - inherited) if roles else []
    return {"capabilities": items, "inherited_count": len(inherited), "supplementary_count": len(supplementary),
            "effective_count": len(origins), "grants": grants,
            "non_delegable": [{"code": k, "label": v["label"], "group_name": v["group_name"], "reason": v["reserved_reason"]}
                              for k, v in catalog.items() if v["reserved"]]}


