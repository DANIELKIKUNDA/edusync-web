-- Module Écoles (plateforme), lot 2026-10. No business rule changes: statuses stay ACTIVE / SUSPENDED / DISABLED.
--
-- 1. Promoter / main contact: the institutional contact of the platform, distinct from the school's own phone and
--    e-mail (used in document headers) and from the technical school administrator (an EduSync account).
ALTER TABLE schools ADD COLUMN IF NOT EXISTS contact_name varchar(160);
ALTER TABLE schools ADD COLUMN IF NOT EXISTS contact_function varchar(120);
ALTER TABLE schools ADD COLUMN IF NOT EXISTS contact_phone varchar(24);
ALTER TABLE schools ADD COLUMN IF NOT EXISTS contact_email varchar(320);

-- 2. EduSync identifier generated by the server (EDS-000001...): unique (schools.code UNIQUE), transactional
--    (sequence), never typed by a user. Existing codes are kept unchanged.
CREATE SEQUENCE IF NOT EXISTS school_code_seq START 1;
DO $$ DECLARE top bigint; BEGIN
  SELECT coalesce(max(substring(code from '^EDS-([0-9]{6,})$')::bigint), 0) INTO top FROM schools;
  IF top > 0 AND top >= (SELECT last_value FROM school_code_seq) THEN PERFORM setval('school_code_seq', top); END IF;
END $$;

-- 3. Server-side search, index-friendly, accent and case insensitive (name, EduSync code, promoter name).
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS unaccent;
CREATE OR REPLACE FUNCTION edusync_search_key(value text) RETURNS text
  LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
  AS $$ SELECT lower(public.unaccent('public.unaccent'::regdictionary, value)) $$;
CREATE INDEX IF NOT EXISTS idx_schools_search_trgm ON schools
  USING gin ((edusync_search_key(name || ' ' || code || ' ' || coalesce(contact_name, ''))) gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_schools_created_id ON schools(created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_schools_name_id ON schools(lower(name), id);

-- 4. "Dernière activité" of a school = most recent activity of a device session opened in its space.
CREATE INDEX IF NOT EXISTS idx_device_sessions_school_seen ON user_device_sessions(school_id, last_seen_at DESC) WHERE school_id IS NOT NULL;

-- 5. Configuration state of many schools in one query. The platform role cannot read the school settings tables
--    (FORCE RLS, tenant only); this function returns only three booleans per school — the existing readiness gates
--    (année scolaire, classes, catalogue des frais) — never a row of those tables.
CREATE OR REPLACE FUNCTION platform_school_setup(p_school uuid)
  RETURNS TABLE(has_year boolean, has_classes boolean, has_fees boolean)
  LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp
  AS $$ SELECT EXISTS (SELECT 1 FROM academic_years WHERE school_id = p_school),
               EXISTS (SELECT 1 FROM school_classes WHERE school_id = p_school AND enabled),
               EXISTS (SELECT 1 FROM fee_types WHERE school_id = p_school AND enabled) $$;
REVOKE ALL ON FUNCTION platform_school_setup(uuid) FROM PUBLIC;
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='edusync_platform') THEN
    GRANT EXECUTE ON FUNCTION platform_school_setup(uuid) TO edusync_platform;
    GRANT EXECUTE ON FUNCTION edusync_search_key(text) TO edusync_platform;
    GRANT USAGE, SELECT ON SEQUENCE school_code_seq TO edusync_platform;
  END IF;
END $$;
