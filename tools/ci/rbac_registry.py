"""Canonical RBAC registry tooling (owner decision 6, 2026-10-23).

contracts/CAPABILITY_REGISTRY.json is the versioned source of truth. The database is derived from it and checked
against it; any drift fails the CI.

    python tools/ci/rbac_registry.py sql            # idempotent SQL reproducing the registry (catalog metadata,
                                                    # standard role baselines, locked capabilities, SoD rules)
    python tools/ci/rbac_registry.py check          # compare the database (EDUSYNC_OWNER_DATABASE_URL) to the registry

Additive only: `sql` never deletes a capability, a role capability or a rule — removing something is a reviewed
migration of its own.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1].parent
REGISTRY = ROOT / "contracts" / "CAPABILITY_REGISTRY.json"


def load() -> dict:
    return json.loads(REGISTRY.read_text(encoding="utf-8"))


def q(v) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (list, dict)):
        return q(json.dumps(v, ensure_ascii=False)) + "::jsonb"
    return "'" + str(v).replace("'", "''") + "'"


def sql(reg: dict) -> str:
    out = [f"-- generated by tools/ci/rbac_registry.py sql from CAPABILITY_REGISTRY.json {reg['registry_version']}"]
    caps = reg["capabilities"]
    cols = "code,domain_name,group_name,label,action_code,risk,offline_policy,audit_required,scope_types,source_status,prerequisites,outputs,sensitive,notes,registry_version,active"
    rows = ",\n".join(
        f"({q(c['code'])},{q(c['domain'])},{q(c['group'])},{q(c['label'])},{q(c['action'])},{q(c['risk'])},{q(c['offline_policy'])},"
        f"{q(c['audit_required'])},{q(c['scope_types'])},{q(c['source_status'])},{q(c.get('prerequisites') or [])},{q(c.get('outputs') or [])},"
        f"{q(c.get('sensitive', False))},{q(c.get('notes', ''))},{q(reg['registry_version'])},true)" for c in caps)
    out.append(f"INSERT INTO capability_catalog({cols}) VALUES\n{rows}\nON CONFLICT (code) DO NOTHING;")
    # lifecycle metadata in two passes (alias_of references another catalog row)
    meta = ",\n".join(f"({q(c['code'])},{q(c['lifecycle'])},{q(c.get('replaced_by'))},{q(c['school_adjustable'])})" for c in caps)
    out.append(f"UPDATE capability_catalog k SET lifecycle=v.lifecycle, replaced_by=v.replaced_by, school_adjustable=v.adj, updated_at=now()\n"
               f"FROM (VALUES\n{meta}\n) AS v(code,lifecycle,replaced_by,adj) WHERE k.code=v.code;")
    alias = ",\n".join(f"({q(c['code'])},{q(c['alias_of'])})" for c in caps if c.get("alias_of"))
    out.append(f"UPDATE capability_catalog k SET alias_of=v.alias_of FROM (VALUES\n{alias}\n) AS v(code,alias_of) WHERE k.code=v.code;")
    for code, role in reg["standard_roles"].items():
        vals = ",".join(q(c) for c in role["capabilities"])
        out.append(f"INSERT INTO rbac_role_capabilities(role_id,capability_code)\n  SELECT r.id, c FROM rbac_roles r, unnest(ARRAY[{vals}]::varchar[]) c\n"
                   f"  WHERE r.code={q(code)} AND r.kind={q(role['kind'])} AND r.school_id IS NULL\nON CONFLICT DO NOTHING;")
        if role.get("locked"):
            vals = ",".join(q(c) for c in role["locked"])
            out.append(f"INSERT INTO rbac_role_constraints(role_id,capability_code,kind)\n  SELECT r.id, c, 'LOCKED' FROM rbac_roles r, unnest(ARRAY[{vals}]::varchar[]) c\n"
                       f"  WHERE r.code={q(code)} AND r.kind={q(role['kind'])} AND r.school_id IS NULL\nON CONFLICT DO NOTHING;")
    for rule in reg["sod_rules"]:
        out.append("INSERT INTO rbac_sod_rules(code,kind,effect,school_overridable,label,description,capabilities,match_prefix) VALUES ("
                   f"{q(rule['code'])},{q(rule['kind'])},{q(rule['effect'])},{q(rule['school_overridable'])},{q(rule['label'])},"
                   f"{q(rule.get('description', ''))},{q(rule.get('capabilities', []))},{q(rule.get('match_prefix'))}) ON CONFLICT (code) DO NOTHING;")
    return "\n".join(out) + "\n"


def check(reg: dict) -> list[str]:
    from sqlalchemy import create_engine, text
    engine = create_engine(os.environ["EDUSYNC_OWNER_DATABASE_URL"])
    problems: list[str] = []
    with engine.begin() as c:
        db = {r["code"]: r for r in c.execute(text(
            "SELECT code,lifecycle,alias_of,replaced_by,school_adjustable,risk,offline_policy,scope_types FROM capability_catalog")).mappings()}
        roles = {}
        for code, cap in c.execute(text("""SELECT r.code, rc.capability_code FROM rbac_roles r JOIN rbac_role_capabilities rc ON rc.role_id=r.id
                WHERE r.kind IN ('SCHOOL_STANDARD','PLATFORM_STANDARD') AND r.school_id IS NULL""")):
            roles.setdefault(code, set()).add(cap)
        locked = {}
        for code, cap in c.execute(text("""SELECT r.code, k.capability_code FROM rbac_role_constraints k JOIN rbac_roles r ON r.id=k.role_id WHERE k.kind='LOCKED'""")):
            locked.setdefault(code, set()).add(cap)
        sod = {r["code"]: r for r in c.execute(text("SELECT code,kind,effect,school_overridable FROM rbac_sod_rules")).mappings()}
    regcaps = {x["code"]: x for x in reg["capabilities"]}
    for code in sorted(set(db) - set(regcaps)):
        problems.append(f"capability in database, missing from the registry: {code}")
    for code in sorted(set(regcaps) - set(db)):
        problems.append(f"capability in the registry, missing from the database: {code}")
    for code in sorted(set(db) & set(regcaps)):
        a, b = db[code], regcaps[code]
        for field, want in (("lifecycle", b["lifecycle"]), ("alias_of", b.get("alias_of")), ("replaced_by", b.get("replaced_by")),
                            ("school_adjustable", b["school_adjustable"]), ("risk", b["risk"]), ("offline_policy", b["offline_policy"]),
                            ("scope_types", b["scope_types"])):
            if a[field] != want:
                problems.append(f"{code}.{field}: database {a[field]!r} != registry {want!r}")
    for code, role in reg["standard_roles"].items():
        got, want = roles.get(code, set()), set(role["capabilities"])
        if got != want:
            problems.append(f"standard role {code}: database +{sorted(got - want)} -{sorted(want - got)}")
        if locked.get(code, set()) != set(role.get("locked", [])):
            problems.append(f"standard role {code}: locked capabilities differ")
    for code in sorted(set(roles) - set(reg["standard_roles"])):
        problems.append(f"standard role in database, missing from the registry: {code}")
    for rule in reg["sod_rules"]:
        d = sod.get(rule["code"])
        if d is None or (d["kind"], d["effect"], d["school_overridable"]) != (rule["kind"], rule["effect"], rule["school_overridable"]):
            problems.append(f"SoD rule {rule['code']} differs")
    return problems


if __name__ == "__main__":
    reg = load()
    if sys.argv[1] == "sql":
        sys.stdout.write(sql(reg))
    elif sys.argv[1] == "check":
        found = check(reg)
        for p in found:
            print("DRIFT", p)
        print(f"registry {reg['registry_version']}: {len(found)} drift(s)")
        sys.exit(1 if found else 0)
